// Run separately with a pinned Playwright installation; all application traffic stays on loopback.
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createGateway } from '../src/server.js';
import { fakeProvider, adminKey } from './helpers.js';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE ?? 'playwright');
const directory = mkdtempSync(join(tmpdir(), 'router4u-browser-'));
const backend = await fakeProvider();
const config = { data_dir: directory, port: 0, routes: [{ id: 'local', profile: 'api_key', base_url: backend.url, key_env: 'FAKE_KEY', enabled: false, models: [], protocols: ['responses', 'chat'] }] };
const gateway = createGateway(config, { environment: { ROUTER4U_ADMIN_KEY: adminKey, FAKE_KEY: 'inert' }, loadConfig: () => config });
const url = await gateway.listen();
let browser;
try {
  browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
  const context = await browser.newContext({ viewport: { width: 1365, height: 900 } });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await context.route('**/*', route => new URL(route.request().url()).origin === url ? route.continue() : route.abort());
  await page.goto(url);
  await page.getByLabel('Operator key').fill(adminKey);
  await page.getByRole('button', { name: 'Open control room' }).click();
  await page.getByRole('heading', { name: 'Make yourself at home' }).waitFor();
  assert.equal(gateway.config.routes[0].enabled, false);
  assert.deepEqual(gateway.config.routes[0].models, []);
  await page.getByRole('link', { name: 'Connections', exact: true }).click();
  await page.getByRole('button', { name: 'Set up models', exact: true }).click();
  await page.getByRole('button', { name: 'Load available models', exact: true }).click();
  await page.getByLabel('Available models', { exact: true }).selectOption(['test-model']);
  await page.getByRole('button', { name: 'Use selected models', exact: true }).click();
  await page.getByLabel('Connection status').selectOption('true');
  await page.getByRole('button', { name: 'Save route', exact: true }).click();
  await page.getByRole('button', { name: 'Edit route', exact: true }).waitFor();
  assert.deepEqual(gateway.config.routes[0].models, ['test-model']);
  assert.equal(gateway.config.routes[0].enabled, true);
  await page.getByRole('link', { name: 'Projects & keys', exact: true }).click();
  await page.getByRole('button', { name: 'Create project', exact: true }).click();
  await page.getByLabel('Project ID', { exact: true }).fill('browser-app');
  await page.getByLabel('Authorized routes').selectOption(['local']);
  await page.getByRole('button', { name: 'Save project', exact: true }).click();
  await page.getByRole('heading', { name: 'browser-app', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Issue project key' }).click();
  const issued = JSON.parse(await page.locator('#detail pre').textContent());
  assert.match(issued.key, /^r4u_/);
  await page.getByRole('button', { name: 'Close', exact: true }).click();
  const response = await fetch(url + '/v1/responses', { method: 'POST', headers: { authorization: `Bearer ${issued.key}`, 'content-type': 'application/json' }, body: JSON.stringify({ model: 'test-model', input: 'Hello', store: false }) });
  assert.equal(response.status, 200); await response.json();
  await page.getByRole('link', { name: 'Requests', exact: true }).click();
  await page.getByLabel('Project', { exact: true }).selectOption('browser-app');
  await page.getByRole('button', { name: 'Details', exact: true }).click();
  assert.match(await page.locator('#detail pre').textContent(), /completed/);
  await page.getByRole('button', { name: 'Close', exact: true }).click();
  await page.getByRole('link', { name: 'Connections', exact: true }).click();
  await page.getByRole('button', { name: 'Edit route', exact: true }).click();
  assert.deepEqual(await page.getByLabel('Authentication profile').locator('option').evaluateAll(options => options.map(option => option.value)), ['codex', 'api_key']);
  await page.getByLabel('Allowed model IDs').fill('test-model, second-model');
  await page.getByRole('button', { name: 'Save route', exact: true }).click();
  await page.getByText('test-model · second-model', { exact: true }).waitFor();
  assert.deepEqual(gateway.config.routes[0].models, ['test-model', 'second-model']);
  await page.getByRole('link', { name: 'Settings', exact: true }).click();
  const editor = page.getByLabel('Configuration JSON');
  const current = JSON.parse(await editor.inputValue()); current.daily_requests = 12345;
  await editor.fill(JSON.stringify(current));
  await page.getByRole('button', { name: 'Save & apply', exact: true }).click();
  await page.getByText('Configuration saved and applied', { exact: true }).waitFor();
  assert.equal(gateway.config.daily_requests, 12345);
  await page.getByRole('link', { name: 'Activity', exact: true }).click();
  await page.getByRole('cell', { name: 'project.policy', exact: true }).waitFor();
  await page.getByRole('link', { name: 'Overview', exact: true }).click();
  await page.getByRole('button', { name: 'Pause admissions', exact: true }).click();
  await page.getByRole('button', { name: 'Resume admissions', exact: true }).waitFor();
  assert.equal(gateway.store.paused(), true);
  await page.getByRole('button', { name: 'Resume admissions', exact: true }).click();
  await page.getByRole('button', { name: 'Pause admissions', exact: true }).waitFor();
  assert.equal(gateway.store.paused(), false);
  await page.reload();
  await page.getByRole('heading', { name: 'Make yourself at home' }).waitFor();
  assert.equal(await page.evaluate(() => localStorage.length + sessionStorage.length), 0);
  const cookies = await context.cookies(); assert.ok(cookies.find(c => c.name === 'r4u_session' && c.httpOnly && c.sameSite === 'Strict'));
  if (process.env.SCREENSHOT_PATH) await page.screenshot({ path: process.env.SCREENSHOT_PATH, fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.getByRole('button', { name: 'Sign out', exact: true }).click();
  await page.getByLabel('Operator key').waitFor();
  assert.equal((await page.request.get(url + '/admin/projects')).status(), 401);
  assert.deepEqual(errors, []);
  console.log('Browser smoke passed: model-free onboarding, discovery and enablement, login, projects, keys, inference, history, route edits, persistent settings, audit, pause/resume, responsive layout, and logout. No live provider contacted.');
} finally {
  await browser?.close(); await gateway.close(); await backend.close(); rmSync(directory, { recursive: true, force: true });
}
